import {writeFileSync} from 'node:fs';
import {getPublicClient} from '../src/clients.ts';
import {readMarket} from '../src/market-view.ts';
import {snapshot,blend,DEFAULT_LIMITS,ladder,planTrade,fadeLadder,completeSetArb} from '../src/trade.ts';
const client=getPublicClient(10,'https://optimism-rpc.publicnode.com');
const address='0xc03bf1725b72ab5765b639c582853ede9afb26a6';
const info=await readMarket(client,10,address);
if(info.payoutReported||info.questions.some(q=>q.is_pending_arbitration)) throw new Error('Reported or arbitrated market');
const snap=await snapshot(client,10,address);
const own=[.85,.09,.02,.04], weight=.25, q=blend(own,snap.implied,weight);
const limits={...DEFAULT_LIMITS,bankroll:180.28};
const sizes=[1,5,10,20,25,40,50,75,100,150,200,300,500,901];
const longs=await ladder(client,snap,0,q,limits,sizes);
const longPlan=planTrade(longs,q,0,limits);
const shorts=await fadeLadder(client,snap,1,q,limits,sizes);
const shortPlan=planTrade(shorts,q,1,limits);
const arb=await completeSetArb(client,snap,10);
const output={at:new Date().toISOString(),block:String(await client.getBlockNumber()),info,snap,own,weight,q,limits,longs,longPlan,shorts,shortPlan,arb};
writeFileSync('research/readiness-live-quotes.json',JSON.stringify(output,(_,v)=>typeof v==='bigint'?String(v):v,2));
console.log(JSON.stringify({at:output.at,block:output.block,q,spot:snap.spot,tradeable:snap.tradeable,longPlan,shortPlan,arb},(_,v)=>typeof v==='bigint'?String(v):v,2));
